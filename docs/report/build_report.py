def latest(pattern: str) -> Path | None:
    c = sorted(REPORTS.glob(pattern))
    return c[-1] if c else None


def model_report(source_pred) -> dict | None:
    for d in sorted(REPORTS.glob("models-*"), reverse=True):
        try:
            r = json.loads((d / "results.json").read_text())
        except (OSError, json.JSONDecodeError):
            continue
        if source_pred(r.get("source", ""), r.get("label", "")):
            r["_dir"] = d.name
            return r
    return None


def scenario_report() -> dict:
    d = [p for p in sorted(REPORTS.glob("2026*")) if (p / "report.json").exists()][-1]
    r = json.loads((d / "report.json").read_text())
    r["_dir"] = d.name
    return r


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def count_lines(globs: list[str]) -> int:
    files = git("ls-files", *globs).splitlines()
    n = 0
    for f in files:
        try:
            n += sum(1 for _ in open(ROOT / f, encoding="utf-8", errors="ignore"))
        except OSError:
            pass
    return n


def count_tests() -> str:
    out = subprocess.run([str(ROOT / "backend/.venv/bin/python"), "-m", "pytest", "-q", "--collect-only"],
                         cwd=ROOT / "backend", capture_output=True, text=True).stdout
    m = re.search(r"(\d+) tests? collected", out)
    return m.group(1) if m else "?"


