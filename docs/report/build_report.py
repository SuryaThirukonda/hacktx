FONT = "Lato, 'DejaVu Sans', Arial, sans-serif"


def svg(w: int, h: int, body: str, title: str) -> str:
    return (f'<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="{esc(title)}" '
            f'xmlns="http://www.w3.org/2000/svg" font-family="{FONT}">'
            f'<defs><marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" '
            f'orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="{INK2}"/></marker></defs>{body}</svg>')


def text(x, y, s, size=12, color=INK1, weight=400, anchor="start", italic=False) -> str:
    st = ' font-style="italic"' if italic else ""
    return (f'<text x="{x}" y="{y}" font-size="{size}" fill="{color}" font-weight="{weight}" '
            f'text-anchor="{anchor}"{st}>{esc(s)}</text>')


def box(x, y, w, h, title, lines=(), color=S[0], status: str | None = None, fill=SURF) -> str:
    out = [f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="8" fill="{fill}" stroke="{AXIS}" stroke-width="1"/>',
           f'<rect x="{x}" y="{y}" width="5" height="{h}" rx="2" fill="{color}"/>',
           text(x + 14, y + 19, title, 12.5, INK1, 700)]
    for i, ln in enumerate(lines):
        out.append(text(x + 14, y + 36 + i * 14.5, ln, 10.5, INK2))
    if status:
        out.append(status_icon(x + w - 14, y + 14, status))
    return "".join(out)


def status_icon(cx, cy, kind) -> str:
    """Status = colour + shape (check / exclamation / cross), never colour alone."""
    _, col, _ = STATUS[kind]
    out = f'<circle cx="{cx}" cy="{cy}" r="7" fill="{col}"/>'
    if kind == "works":
        out += f'<path d="M{cx - 3.4},{cy + 0.2} l2.4,2.4 l4.4,-4.8" fill="none" stroke="#fff" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/>'
    elif kind == "partial":
        out += f'<line x1="{cx}" y1="{cy - 3.6}" x2="{cx}" y2="{cy + 0.8}" stroke="#fff" stroke-width="1.8" stroke-linecap="round"/>'
        out += f'<circle cx="{cx}" cy="{cy + 3.4}" r="1.1" fill="#fff"/>'
    else:
        out += f'<path d="M{cx - 2.8},{cy - 2.8} l5.6,5.6 M{cx + 2.8},{cy - 2.8} l-5.6,5.6" stroke="#fff" stroke-width="1.8" stroke-linecap="round"/>'
    return out


def status_legend(x, y) -> str:
    out = []
    for k in ("works", "partial", "todo"):
        label = STATUS[k][0]
        out.append(status_icon(x + 7, y - 4, k) + text(x + 19, y, label, 10.5, INK2))
        x += 34 + len(label) * 5.8
    return "".join(out)


def arrow(x1, y1, x2, y2, label="", lx=None, ly=None, dashed=False, color=INK2) -> str:
    d = ' stroke-dasharray="5 4"' if dashed else ""
    out = f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{color}" stroke-width="1.4"{d} marker-end="url(#ah)"/>'
    if label:
        lx = (x1 + x2) / 2 if lx is None else lx
        ly = (y1 + y2) / 2 - 5 if ly is None else ly
        out += text(lx, ly, label, 9.5, INK3, 400, "middle", italic=True)
    return out


def path_arrow(d: str, label="", lx=0, ly=0, dashed=False) -> str:
    da = ' stroke-dasharray="5 4"' if dashed else ""
    out = f'<path d="{d}" fill="none" stroke="{INK2}" stroke-width="1.4"{da} marker-end="url(#ah)"/>'
    if label:
        out += text(lx, ly, label, 9.5, INK3, 400, "middle", italic=True)
    return out


def legend(items, x, y) -> str:
    out, cx = [], x
    for name, color in items:
        out.append(f'<rect x="{cx}" y="{y - 9}" width="11" height="11" rx="2" fill="{color}"/>')
        out.append(text(cx + 16, y, name, 10.5, INK2))
        cx += 26 + len(name) * 5.6
    return "".join(out)


def hbar_chart(rows: list[tuple[str, float, str]], title: str, w=700, unit="", vmax=1.0, color=S[0],
               note_color=INK3) -> str:
    """Single-series horizontal bars (no legend needed: the title names the series). rows: (label, value, note)."""
    lw, bh, gap, top = 230, 9, 4, 26
    pw = w - lw - 120
    h = top + len(rows) * (bh + gap) + 24
    out = [text(0, 14, title, 12, INK1, 700)]
    for t in (0, 0.25, 0.5, 0.75, 1.0):
        x = lw + pw * t
        out.append(f'<line x1="{x}" y1="{top - 4}" x2="{x}" y2="{h - 18}" stroke="{GRID}" stroke-width="1"/>')
        out.append(text(x, h - 4, f"{t * vmax:g}{unit}", 9.5, INK3, 400, "middle"))
    for i, (label, v, note) in enumerate(rows):
        y = top + i * (bh + gap)
        out.append(text(lw - 8, y + bh - 2, label, 10.5, INK2, 400, "end"))
        bw = max(1.5, pw * min(v, vmax) / vmax)
        out.append(f'<path d="M{lw},{y} h{bw - 3} a3,3 0 0 1 3,3 v{bh - 6} a3,3 0 0 1 -3,3 h{-(bw - 3)} z" fill="{color}"/>')
        out.append(text(lw + bw + 6, y + bh - 2, f"{v:.3f}{unit}" + (f"  {note}" if note else ""), 10, note_color))
    return svg(w, h, "".join(out), title)


def grouped_bars(cats: list[str], series: list[tuple[str, str, list[float | None]]], title: str, w=700, h=250,
                 ylab="recall") -> str:
    left, right, top, bottom = 46, 12, 44, 40
    pw, ph = w - left - right, h - top - bottom
    out = [text(0, 14, title, 12, INK1, 700)]
    if len(series) > 1:  # one series: the title names it
        out.append(legend([(n, c) for n, c, _ in series], left, 32))
    for t in (0, 0.25, 0.5, 0.75, 1.0):
        y = top + ph * (1 - t)
        out.append(f'<line x1="{left}" y1="{y}" x2="{w - right}" y2="{y}" stroke="{GRID}" stroke-width="1"/>')
        out.append(text(left - 6, y + 3.5, f"{t:g}", 9.5, INK3, 400, "end"))
    out.append(text(12, top + ph / 2, ylab, 9.5, INK3, 400, "middle").replace("<text", f'<text transform="rotate(-90 12 {top + ph / 2})"'))
    gw = pw / len(cats)
    n = len(series)
    bw = min(26, (gw - 18) / n - 2)
    for ci, cat in enumerate(cats):
        gx = left + gw * ci + (gw - (bw + 2) * n) / 2
        for si, (_, color, vals) in enumerate(series):
            v = vals[ci]
            x = gx + si * (bw + 2)
            if v is None:
                out.append(text(x + bw / 2, top + ph - 4, "–", 10, INK3, 400, "middle"))
                continue
            bh = max(1.5, ph * v)
            y = top + ph - bh
            r = min(3, bh / 2, bw / 2)
            out.append(f'<path d="M{x},{top + ph} v{-(bh - r)} a{r},{r} 0 0 1 {r},{-r} h{bw - 2 * r} '
                       f'a{r},{r} 0 0 1 {r},{r} v{bh - r} z" fill="{color}"/>')
            if v >= 0.05:
                out.append(text(x + bw / 2, y - 3, f"{v:.2f}", 8.5, INK2, 400, "middle"))
        out.append(text(left + gw * ci + gw / 2, top + ph + 16, cat, 10.5, INK2, 400, "middle"))
    out.append(f'<line x1="{left}" y1="{top + ph}" x2="{w - right}" y2="{top + ph}" stroke="{AXIS}" stroke-width="1"/>')
    return svg(w, h, "".join(out), title)


def latency_recall(points: list[tuple[str, float, float, str]], title: str, w=700, h=230) -> str:
    """Dot plot: recall (y) vs p50 latency on a log x axis; points labelled directly."""
    import math

    left, right, top, bottom = 46, 20, 28, 36
    pw, ph = w - left - right, h - top - bottom
    lo, hi = 1.0, 2000.0

    def X(ms):
        return left + pw * (math.log10(ms) - math.log10(lo)) / (math.log10(hi) - math.log10(lo))

    out = [text(0, 14, title, 12, INK1, 700)]
    for t in (0, 0.5, 1.0):
        y = top + ph * (1 - t)
        out.append(f'<line x1="{left}" y1="{y}" x2="{w - right}" y2="{y}" stroke="{GRID}"/>')
        out.append(text(left - 6, y + 3.5, f"{t:g}", 9.5, INK3, 400, "end"))
    for ms in (1, 10, 100, 1000):
        out.append(f'<line x1="{X(ms)}" y1="{top}" x2="{X(ms)}" y2="{top + ph}" stroke="{GRID}"/>')
        out.append(text(X(ms), top + ph + 14, f"{ms} ms", 9.5, INK3, 400, "middle"))
    out.append(text(left + pw / 2, h - 4, "p50 latency per frame (log scale, CPU)", 9.5, INK3, 400, "middle"))
    for label, ms, rec, color in points:
        x, y = X(ms), top + ph * (1 - rec)
        out.append(f'<circle cx="{x}" cy="{y}" r="5.5" fill="{color}" stroke="{PAGE}" stroke-width="2"/>')
        out.append(text(x + 9, y + 4, f"{label}  (R {rec:.2f}, {ms:.0f} ms)", 10, INK2))
    return svg(w, h, "".join(out), title)


