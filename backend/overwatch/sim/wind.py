"""Wind for the simulated drones: a steady component plus Dryden turbulence (low-altitude form).

Low-altitude Dryden (MIL-F-8785C / MIL-HDBK-1797), with h in feet and W20 the wind speed at 20 ft:
  sigma_w = 0.1 W20, sigma_u = sigma_v = sigma_w / (0.177 + 0.000823 h)^0.4,
  L_w = h, L_u = L_v = h / (0.177 + 0.000823 h)^1.2.
Each axis is generated by a first-order shaping filter with time constant L/V (exact for the u axis; an
approximation for v and w, whose Dryden spectra are second order). Altitude is clamped to 10..1000 ft.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

FT = 0.3048


@dataclass
class DrydenWind:
    w20_mps: float  # wind speed at 20 ft (about 6 m)
    alt_m: float
    airspeed_mps: float = 5.0
    steady_mps: tuple[float, float] = (0.0, 0.0)  # steady wind east, north
    seed: int = 0
    _g: np.ndarray = field(default_factory=lambda: np.zeros(3), repr=False)

    def __post_init__(self) -> None:
        self.rng = np.random.default_rng(self.seed)

    def sigmas_and_scales(self) -> tuple[np.ndarray, np.ndarray]:
        h = min(1000.0, max(10.0, self.alt_m / FT))
        w20 = self.w20_mps / FT
        s_w = 0.1 * w20
        s_uv = s_w / (0.177 + 0.000823 * h) ** 0.4
        l_w = h
        l_uv = h / (0.177 + 0.000823 * h) ** 1.2
        return np.array([s_uv, s_uv, s_w]) * FT, np.array([l_uv, l_uv, l_w]) * FT

    def step(self, dt: float) -> np.ndarray:
        """Gust (u, v, w) in m/s after ``dt``: along-track, cross-track, vertical."""
        sig, L = self.sigmas_and_scales()
        V = max(1.0, self.airspeed_mps)
        a = np.exp(-V * dt / L)
        self._g = a * self._g + sig * np.sqrt(1.0 - a * a) * self.rng.standard_normal(3)
        return self._g.copy()

    def total(self, dt: float) -> np.ndarray:
        g = self.step(dt)
        return np.array([self.steady_mps[0] + g[0], self.steady_mps[1] + g[1], g[2]])


@dataclass
class EnergyBattery:
    """Battery state from energy: power at hover from the profile, rising with airspeed (shape assumed)."""

    capacity_wh: float
    hover_w: float
    usable_fraction: float = 0.9
    k_speed: float = 0.012  # assumed: +1.2% power per (m/s)^2 above hover
    used_wh: float = 0.0

    def power_w(self, speed_mps: float, climb_mps: float = 0.0, mass_kg: float = 0.249) -> float:
        return self.hover_w * (1.0 + self.k_speed * speed_mps ** 2) + max(0.0, climb_mps) * mass_kg * 9.81 / 0.5

    def step(self, dt: float, speed_mps: float, climb_mps: float = 0.0) -> float:
        self.used_wh += self.power_w(speed_mps, climb_mps) * dt / 3600.0
        return self.percent()

    def percent(self) -> float:
        return max(0.0, 100.0 * (1.0 - self.used_wh / (self.capacity_wh * self.usable_fraction)))

    def minutes_left(self, speed_mps: float = 0.0) -> float:
        left = self.capacity_wh * self.usable_fraction - self.used_wh
        return max(0.0, left / self.power_w(speed_mps) * 60.0)


def gust_statistics(samples: np.ndarray) -> dict[str, float]:
    return {"std_u": float(samples[:, 0].std()), "std_v": float(samples[:, 1].std()), "std_w": float(samples[:, 2].std()),
            "lag1_u": float(np.corrcoef(samples[:-1, 0], samples[1:, 0])[0, 1])}


