#!/usr/bin/env python
"""Export JSON Schemas for every wire contract (schemas/*.json) so other clients can validate messages, and generate
the dashboard's TypeScript types for the incident model (dashboard/src/types/incident.ts)."""

from __future__ import annotations

import inspect
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pydantic import BaseModel  # noqa: E402

from overwatch import schemas  # noqa: E402
from overwatch.config import REPO_ROOT  # noqa: E402
from overwatch.incident import models as incident_models  # noqa: E402

INCIDENT_TYPES = ["Incident", "SensorSource", "Observation", "ObservationView", "Review", "Track", "SceneAnchor",
                  "Alert", "MissionAction", "IncidentEvent", "Transform"]


def models_of(module) -> list[tuple[str, type[BaseModel]]]:
    return [(n, o) for n, o in inspect.getmembers(module, inspect.isclass)
            if issubclass(o, BaseModel) and o.__module__ == module.__name__ and n != "Msg"]


def ts_type(s: dict, defs: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts_type(x, defs) for x in s["anyOf"]))
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "const" in s:
        return json.dumps(s["const"])
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(x, defs) for x in s["prefixItems"]) + "]"
        return f"{ts_type(s.get('items', {}), defs)}[]"
    if t == "object":
        if "additionalProperties" in s and isinstance(s["additionalProperties"], dict):
            return f"Record<string, {ts_type(s['additionalProperties'], defs)}>"
        return "Record<string, unknown>"
    return "unknown"


def ts_interface(name: str, s: dict, defs: dict) -> str:
    req = set(s.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, ps in s.get("properties", {}).items():
        opt = "" if prop in req else "?"
        lines.append(f"  {prop}{opt}: {ts_type(ps, defs)};")
    lines.append("}")
    return "\n".join(lines)


def generate_ts() -> str:
    defs: dict[str, dict] = {}
    for name in INCIDENT_TYPES:
        sch = getattr(incident_models, name).model_json_schema(mode="serialization")
        defs.update(sch.pop("$defs", {}))
        defs[name] = sch
    out = ["// Generated by backend/scripts/export_schemas.py from overwatch/incident/models.py. Do not edit.",
           f"export const INCIDENT_SCHEMA_VERSION = {json.dumps(incident_models.SCHEMA_VERSION)};", ""]
    for name in sorted(defs):
        s = defs[name]
        if s.get("type") == "object" or "properties" in s:
            out.append(ts_interface(name, s, defs))
        else:
            out.append(f"export type {name} = {ts_type(s, defs)};")
        out.append("")
    return "\n".join(out)


def main() -> int:
    out = REPO_ROOT / "schemas"
    out.mkdir(exist_ok=True)
    n = 0
    for name, obj in models_of(schemas):
        (out / f"{name}.json").write_text(json.dumps(obj.model_json_schema(), indent=2))
        n += 1
    inc_dir = out / "incident"
    inc_dir.mkdir(exist_ok=True)
    for name in INCIDENT_TYPES:
        (inc_dir / f"{name}.json").write_text(json.dumps(getattr(incident_models, name).model_json_schema(), indent=2))
        n += 1
    ts_path = REPO_ROOT / "dashboard" / "src" / "types" / "incident.ts"
    ts_path.write_text(generate_ts())
    print(f"wrote {n} schemas to {out} and {ts_path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
